/**
 * BharatImpact — Domain-Specific Economic Knowledge Graph Data Models
 * Grounded in official Indian macroeconomic transmission channels (MoSPI HCES, PPAC, DGFT, RBI, WSTS).
 * Provides rich, distinct datasets for each selectable domain:
 * 1. Semiconductors (matches reference screenshot)
 * 2. Petrol & Diesel
 * 3. LPG / CNG
 * 4. Food & Agriculture
 * 5. Currency & Markets
 * 6. Shipping & Trade
 * 7. Energy
 * 8. All Domains (Composite Macro Overview)
 */

export type NodeCategoryType =
  | 'global-event'
  | 'commodity'
  | 'supply-chain'
  | 'indian-economy'
  | 'sector'
  | 'household'
  | 'investment';

export type EdgeKindType = 'observed' | 'inferred' | 'potential';

export interface DomainNode {
  id: string;
  label: string;
  category: NodeCategoryType;
  categoryLabel: string;
  stage: number; // 0: Global Event, 1: Commodity/Supply Chain, 2: Indian Economy, 3: Sectors, 4: Household, 5: Investment
  impactBadge: string;
  impactDescription: string;
  impactType: 'positive' | 'negative' | 'neutral';
  icon: string;
  x: number;
  y: number;
  description: string;
  detailedCategory: string;
  severity: 'High' | 'Medium' | 'Moderate' | 'Low';
  timeHorizon: string;
  relatedSectors: string[];
  evidence: {
    source: string;
    tableOrSeries: string;
    vintageYear: string;
    unit: string;
    verificationStatus: '[VERIFIED]' | '[INFERENCE]' | '[UNVERIFIED]';
    publisher: string;
    methodologyNote: string;
  };
  news: {
    headline: string;
    source: string;
    timestamp: string;
  }[];
}

export interface DomainEdge {
  id: string;
  from: string;
  to: string;
  relationType: string;
  kind: EdgeKindType;
  label?: string;
  transmissionLag?: string;
  confidence?: 'High' | 'Medium' | 'Moderate' | 'Hypothetical';
  evidence?: string;
}

export interface KeyImpactMetric {
  id: string;
  label: string;
  value: string;
  direction: 'up' | 'down' | 'neutral';
  subtitle: string;
}

export interface PriceChartSeries {
  title: string;
  seriesA: { name: string; color: string; values: number[] };
  seriesB: { name: string; color: string; values: number[] };
  months: string[];
  tooltipMonthIndex: number;
  tooltipData: {
    month: string;
    labelA: string;
    valA: string;
    labelB: string;
    valB: string;
  };
}

export interface AffectedSectorItem {
  id: string;
  name: string;
  icon: string;
  percentage: number;
  color: string;
  targetNodeId?: string;
}

export interface PathwayInsightsData {
  keyTakeaways: string[];
  riskOutlook: string[];
  highlightEdgeIds?: Record<number, string[]>;
}

export interface DomainGraphDataset {
  domainId: string;
  domainName: string;
  domainIcon: string;
  title: string;
  subtitle: string;
  defaultSelectedNodeId: string;
  nodes: DomainNode[];
  edges: DomainEdge[];
  keyMetrics: KeyImpactMetric[];
  priceChart: PriceChartSeries;
  affectedSectors: AffectedSectorItem[];
  pathwayInsights: PathwayInsightsData;
}

