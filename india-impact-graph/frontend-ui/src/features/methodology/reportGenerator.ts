import {
  APPROACH_STAGES,
  DATA_SOURCES_REGISTRY,
  ANALYTICAL_MODELS,
  CALCULATION_FORMULAS,
  VALIDATION_METRICS,
  METHODOLOGY_LIMITATIONS,
} from './methodologyData';

/**
 * Generates a comprehensive, verifiable Markdown report of BharatImpact's
 * analytical methodology, data sources, calculation models, and limitations.
 */
export function generateMethodologyReportText(): string {
  const currentDate = new Date().toISOString().split('T')[0];

  return `# BharatImpact Methodology & Technical Architecture Report
Generated on: ${currentDate}
System: BharatImpact — Global Events → Indian Economy → Your Household
Repository: arpitcarpenter34-stack/SANKALP

---

## 1. Executive Summary & Purpose
BharatImpact is an evidence-first macroeconomic transmission engine that links global geopolitical and commodity shocks directly to:
1. Indian macroeconomic indicators (Current Account Deficit, Wholesale Price Inflation, Trade Balance).
2. Domestic industrial sector costs and margins (Logistics, FMCG, Agriculture, Chemicals).
3. Itemized Indian household consumption budgets (Fuel, Food, Transport, Utilities) anchored to official survey microdata.
4. Systematic Investment Plan (SIP) affordability and long-term portfolio wealth preservation.

---

## 2. Six-Stage Multi-Layered Analytical Workflow
${APPROACH_STAGES.map(
  (stage) => `### Stage ${stage.stepNumber}: ${stage.title}
- **Overview**: ${stage.shortDesc}
- **Detailed Mechanism**: ${stage.fullDesc}
- **Implemented Code**: ${stage.implementedMechanism}
- **Documented Limitations**: ${stage.limitations}
`
).join('\n')}

---

## 3. Verified Primary Data Sources Registry
BharatImpact adheres to strict provenance verification. Below are the verified primary data sources:

| Source ID | Provider / Publisher | Category | Integration Status | Update Cadence | Key Series / Table |
|:---|:---|:---|:---|:---|:---|
${DATA_SOURCES_REGISTRY.map(
  (src) =>
    `| ${src.id} | ${src.publisher} | ${src.category} | ${src.integrationStatus.toUpperCase()} | ${src.frequency} | ${src.name} |`
).join('\n')}

### Source Notes & Caveats:
${DATA_SOURCES_REGISTRY.map(
  (src) => `- **${src.name} (${src.id})**: ${src.caveats} (Attribution: ${src.attribution})`
).join('\n')}

---

## 4. Analytical Models & Techniques
${ANALYTICAL_MODELS.map(
  (model) => `### ${model.name} (${model.category.toUpperCase()})
- **Purpose**: ${model.purpose}
- **Inputs**: ${model.inputData.join(', ')}
- **Processing Steps**:
${model.processingSteps.map((step) => `  1. ${step}`).join('\n')}
- **Output**: ${model.output}
- **Assumptions**: ${model.assumptions.join('; ')}
- **Limitations**: ${model.limitations.join('; ')}
`
).join('\n')}

---

## 5. Mathematical Calculation Formulas & Worked Logic
${CALCULATION_FORMULAS.map(
  (form) => `### ${form.stageName}
- **Formula**: \`${form.formulaPlain}\`
- **Description**: ${form.description}
- **Variables**:
${form.variables.map((v) => `  - \`${v.symbol}\` (${v.name}): ${v.description} [${v.unit}]`).join('\n')}
- **Worked Verification**:
  - Inputs: ${JSON.stringify(form.workedExample.inputValues)}
  - Steps: ${form.workedExample.calculationSteps.join(' -> ')}
  - Result: ${form.workedExample.finalResult}
`
).join('\n')}

---

## 6. Model Accuracy, Evaluation & Test Verification
${VALIDATION_METRICS.map(
  (metric) => `### ${metric.title}: ${metric.scoreOrPct}
- **Metric Type**: ${metric.metricType}
- **Benchmark Status**: ${metric.benchmarkStatus}
- **Evaluation Method**: ${metric.evaluationMethod}
- **Sample Size**: ${metric.sampleSize} (${metric.evaluationPeriod})
- **Limitations**: ${metric.limitations}
`
).join('\n')}

---

## 7. Known System Constraints & Transparency Disclaimers
${METHODOLOGY_LIMITATIONS.map(
  (lim) => `### ${lim.title}
- **Affected Features**: ${lim.affectedFeature}
- **Unavailable Capability**: ${lim.whatIsUnavailable}
- **Workaround in Place**: ${lim.workaroundInPlace}
- **Future Enhancement**: ${lim.futureCapabilityNeeded}
`
).join('\n')}

---

## 8. Financial Advice Disclaimer
The calculations, scenario simulations, and household budget models generated by BharatImpact are provided for educational, analytical, and informational purposes. They do not constitute registered financial, investment, legal, or tax advice under SEBI (Securities and Exchange Board of India) regulations. Past performance, econometric elasticity factors, and scenario projections do not guarantee future economic or portfolio returns.
`;
}

/**
 * Triggers an authentic client-side file download for the Methodology Report.
 */
export function downloadMethodologyReport(): void {
  const reportContent = generateMethodologyReportText();
  const blob = new Blob([reportContent], { type: 'text/markdown;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const downloadLink = document.createElement('a');

  const dateStr = new Date().toISOString().split('T')[0];
  downloadLink.href = url;
  downloadLink.setAttribute('download', `BharatImpact_Methodology_Report_${dateStr}.md`);
  document.body.appendChild(downloadLink);
  downloadLink.click();
  document.body.removeChild(downloadLink);
  URL.revokeObjectURL(url);
}
